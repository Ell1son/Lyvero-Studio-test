const LANGS = ["en", "ru", "et"];
let lang = "en",
  cat = "all";
try {
  const s = localStorage.getItem("lang");
  if (LANGS.includes(s)) lang = s;
} catch (e) {}

const grid = document.getElementById("grid"),
  filters = document.getElementById("filters");
const esc = (s) =>
  s.replace(
    /[&<>"]/g,
    (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c],
  );
const t = (k) => T[k][LANGS.indexOf(lang)];

function render() {
  document.documentElement.lang = lang;
  document.title = t("title");
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.innerHTML = t(el.dataset.i18n);
  });
  document
    .querySelectorAll("#lang button")
    .forEach((b) => b.setAttribute("aria-pressed", b.dataset.lang === lang));

  const cats = ["all", ...new Set(works.map((w) => w.cat))];
  filters.innerHTML = cats
    .map(
      (c) =>
        `<button type="button" data-cat="${c}" aria-pressed="${c === cat}">${c === "all" ? t("all") : t("cat_" + c)}</button>`,
    )
    .join("");

  const i = LANGS.indexOf(lang);
  grid.innerHTML = works
    .filter((w) => cat === "all" || w.cat === cat)
    .map(
      (w) => `
<a class="work" href="${esc(w.url)}"${w.url !== "#" ? ' target="_blank" rel="noopener"' : ""}>
  <div class="shot"><div class="bar"><i></i><i></i><i></i></div>
    ${
      w.img
        ? `<img src="${esc(w.img)}" alt="${esc(w.title[i])}" loading="lazy">`
        : `<div class="page" style="background:${w.c2}">
      <b style="background:${w.c1}"></b><span style="background:${w.c1}"></span><span style="background:${w.c1}"></span><em style="background:${w.c1}"></em>
      <div class="blocks"><u style="background:${w.c1}"></u><u style="background:${w.c1}"></u><u style="background:${w.c1}"></u></div></div>`
    }
  </div>
  <h3>${esc(w.title[i])}</h3><p><span class="tag">${t("cat_" + w.cat)}</span> · ${esc(w.desc[i])}</p>
</a>`,
    )
    .join("");
}

filters.addEventListener("click", (e) => {
  const b = e.target.closest("button");
  if (!b) return;
  cat = b.dataset.cat;
  render();
});
document.getElementById("lang").addEventListener("click", (e) => {
  const b = e.target.closest("button");
  if (!b) return;
  lang = b.dataset.lang;
  try {
    localStorage.setItem("lang", lang);
  } catch (err) {}
  render();
});
document.getElementById("y").textContent = new Date().getFullYear();
render();
